// "Portable" Mermaid (row 83, prototype portable.js): plain Mermaid enriched with classDef / class / style /
// linkStyle lines generated from the resolved studio styles, so stock renderers (YouTrack, GitHub) show the same
// colours. Sequence and ER diagrams pass through with the `%%@` lines removed.
//
// What mmdx draws beyond Mermaid (T10 §4.6): icons are label tokens (`fa:fa-cog Running`), which are code and stay as
// they are (stock Mermaid draws `fa*` tokens and shows other packs' as text); metadata images (`img` on mindmap nodes,
// states, participants) and catalogue shapes in metadata (`shape`) have no Mermaid syntax, so the portable file drops
// them with the rest of the metadata — `mmdxOnlyContent` lists them, and the editor says so on export.
//
// Unlike the prototype, the colour resolver is a parameter (never a module global) and every value goes through
// the render style validation: an unresolvable `@ref`, or anything that is not a colour / number / dash pattern,
// is dropped instead of being written into the output.
import { NO_ICONS } from '../icons/names.js';
import { withKind } from '../kinds/registry.js';
import { META_HEADER } from '../meta/index.js';
import { KIND_TO_COLL } from '../meta/types.js';
import type { DiagramMeta, ItemMeta } from '../meta/types.js';
import type { DiagramModel, FlowchartModel, SupportedModel } from '../model.js';
import type { DiagramType, ItemRef } from '../types.js';
import { mergeStyle, pickStyle } from '../render/common.js';
import { edgeMeta, edgePreset, flowPresets, groupPreset, nodePreset } from '../render/flow-presets.js';
import type { RenderContext } from '../render/types.js';
import type { StyleProps } from '../style.js';
import { createStaticMeasurer } from '../text/measure.js';
import type { ResolvedTheme } from '../theme/types.js';
import { DEFAULT_IMAGE_POLICY, DEFAULT_LINK_POLICY } from '../validate.js';

export type ColorResolver = (v: unknown) => string | undefined;

export const PORTABLE_MARKER = '%% ---- generated by diagram-studio (portable styles) ----';

const NODE_CSS: readonly [keyof StyleProps, string][] = [['fill', 'fill'], ['stroke', 'stroke'], ['strokeWidth', 'stroke-width'], ['text', 'color']];

// Values are already validated (colour literals, finite numbers), so they cannot break out of the CSS list.
function css(st: StyleProps): string {
  const out: string[] = [];
  for (const [k, prop] of NODE_CSS) {
    const v = st[k];
    if (v === undefined || v === null || v === '') continue;
    out.push(`${prop}:${typeof v === 'number' ? `${v}px` : String(v)}`);
  }
  return out.join(',');
}

/** The Mermaid code without `%%@` metadata lines (and their header), ending with one newline. */
export function stripMetaLines(code: string): string {
  return code.split('\n').filter((l) => !/^\s*%%@/.test(l) && l.trim() !== META_HEADER).join('\n').trimEnd() + '\n';
}

/** The items whose metadata image or catalogue shape the portable file leaves out (mmdx only). */
export interface MmdxOnly {
  images: ItemRef[];
  shapes: ItemRef[];
}

/**
 * What a portable export of `model` leaves out (in model order): items with a metadata image (`img`; an image not
 * chosen yet, `""`, is no content) or a metadata `shape`. Metadata of items the code no longer has does not count.
 */
export function mmdxOnlyContent(meta: DiagramMeta, model: DiagramModel): MmdxOnly {
  const out: MmdxOnly = { images: [], shapes: [] };
  for (const ref of withKind(model, (k, m) => k.items(m)) ?? []) {
    const coll = Object.hasOwn(KIND_TO_COLL, ref.kind) ? KIND_TO_COLL[ref.kind as keyof typeof KIND_TO_COLL] : undefined;
    const m = coll ? (meta[coll]?.[ref.id] as ItemMeta | undefined) : undefined;
    if (!m) continue;
    if (typeof m.img === 'string' && m.img) out.images.push(ref);
    if (typeof m.shape === 'string' && m.shape) out.shapes.push(ref);
  }
  return out;
}

/**
 * Portable Mermaid for `.mmd` export: `code` is the Mermaid part (any `%%@` lines in it are removed), `meta` its
 * metadata, `model` = parse(code), `theme` the active resolved theme and `color` its colour resolver
 * (`createColorResolver(theme, diagramPaletteOf(meta.styles))`).
 */
export function toPortableMermaid(code: string, meta: DiagramMeta, model: DiagramModel, theme: ResolvedTheme, color: ColorResolver): string {
  const base = stripMetaLines(code);
  const styles = model.type ? PORTABLE_STYLES[model.type] : undefined;
  if (!model.type || !styles) return base;
  const ctx: RenderContext = { color, measure: createStaticMeasurer(), idPrefix: '', linkPolicy: DEFAULT_LINK_POLICY, imagePolicy: DEFAULT_IMAGE_POLICY, icons: NO_ICONS };
  return [base.trimEnd(), '', PORTABLE_MARKER, ...styles(model, meta, theme, ctx)].join('\n') + '\n';
}

/** Style lines per diagram type (the types without any pass through with the `%%@` lines removed). */
const PORTABLE_STYLES: Partial<Record<DiagramType, (model: SupportedModel, meta: DiagramMeta, theme: ResolvedTheme, ctx: RenderContext) => string[]>> = {
  flowchart: (model, meta, theme, ctx) => flowchartStyles(model as FlowchartModel, meta, theme, ctx),
};

function flowchartStyles(model: FlowchartModel, meta: DiagramMeta, theme: ResolvedTheme, ctx: RenderContext): string[] {
  const P = flowPresets(theme, meta);
  const F = theme.flowchart;
  const out: string[] = [];
  const byClass = new Map<string, string[]>();
  for (const n of model.nodes.values()) {
    const preset = nodePreset(n, meta, P);
    const own = pickStyle(meta.nodes?.[n.id]);
    if (NODE_CSS.some(([k]) => own[k] !== undefined)) {
      const c = css(mergeStyle(ctx, F.node, P.node[preset], own));
      if (c) out.push(`style ${n.id} ${c}`);
    } else {
      const k = preset || '_default';
      (byClass.get(k) ?? byClass.set(k, []).get(k)!).push(n.id);
    }
  }
  for (const [k, ids] of byClass) {
    const c = css(mergeStyle(ctx, F.node, k === '_default' ? undefined : P.node[k]));
    if (!c) continue;
    const name = k === '_default' ? 'studioDefault' : `s_${k.replace(/\W/g, '_')}`;
    out.push(`classDef ${name} ${c}`);
    out.push(`class ${ids.join(',')} ${name}`);
  }
  for (const g of model.groups.values()) {
    const st = mergeStyle(ctx, F.group, P.group[groupPreset(g, meta, P)], pickStyle(meta.groups?.[g.id]));
    const { text: _text, ...rest } = st; // a group's text colour is its title colour
    const fill = st.fill === 'none' ? 'transparent' : st.fill;
    const c = css({ ...rest, ...(fill !== undefined ? { fill } : {}), ...(st.titleColor !== undefined ? { text: st.titleColor } : {}) });
    if (c) out.push(`style ${g.id} ${c}`);
  }
  for (const e of model.edges) {
    const st = mergeStyle(ctx, F.edge, P.edge[edgePreset(e, meta, P)], pickStyle(edgeMeta(e, meta)));
    const parts: string[] = [];
    if (st.color) parts.push(`stroke:${st.color}`);
    if (st.width !== undefined) parts.push(`stroke-width:${st.width}px`);
    const label = st.labelColor || st.color;
    if (label) parts.push(`color:${label}`);
    if (st.dash) parts.push(`stroke-dasharray:${st.dash.replace(/\s+/g, ' ')}`);
    if (parts.length) out.push(`linkStyle ${e.index} ${parts.join(',')}`);
  }
  return out;
}
